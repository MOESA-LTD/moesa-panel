// Writes app/src/@types/maskedFields.generated.ts from public.field_class: the sensitive fields of
// each table, which the `api` views return null when the user may not read them. The app types
// those fields nullable from it (app/src/@types/database.ts). Run by `pnpm dev:supabase-types`;
// `--check` only compares the committed file with the database (see masked-fields.test.mjs).
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { psql, ROOT } from './seed-story.mjs';

export const OUTPUT = path.join(ROOT, 'app', 'src', '@types', 'maskedFields.generated.ts');

export const SENSITIVE_SQL =
   "SELECT replace(resource_name, 'public.', '') || '|' || field FROM public.field_class WHERE class = 'sensitive' ORDER BY 1;";

/** "table|field" lines into sorted [table, field] pairs. */
export const parseRows = (output) =>
   output
      .split(/\r?\n/)
      .filter(Boolean)
      .map((line) => line.split('|'))
      .sort(([a, x], [b, y]) => a.localeCompare(b) || x.localeCompare(y));

/** The TypeScript source for the pairs. */
export function render(pairs) {
   const tables = new Map();
   for (const [table, field] of pairs) tables.set(table, [...(tables.get(table) ?? []), field]);
   const entries = [...tables].map(
      ([table, fields]) => `   ${table}: [${fields.map((field) => `'${field}'`).join(', ')}]`
   );
   return [
      '// Generated by scripts/masked-fields.mjs from public.field_class (class sensitive). Do not edit:',
      '// run `pnpm dev:supabase-types` after a change of the classification.',
      'export const MASKED_FIELDS = {',
      entries.join(',\n'),
      '} as const;',
      ''
   ].join('\n');
}

/** The [table, field] pairs a generated file lists, however it was formatted. */
export function parseGenerated(source) {
   const body = source.slice(source.indexOf('{') + 1, source.lastIndexOf('}'));
   const pairs = [];
   for (const [, table, list] of body.matchAll(/(\w+):\s*\[([^\]]*)\]/g)) {
      for (const [, field] of list.matchAll(/'(\w+)'/g)) pairs.push([table, field]);
   }
   return pairs.sort(([a, x], [b, y]) => a.localeCompare(b) || x.localeCompare(y));
}

export const fetchPairs = (sql = psql) => parseRows(sql(SENSITIVE_SQL));

function main() {
   const pairs = fetchPairs();
   if (!pairs.length) throw new Error('public.field_class lists no sensitive field');
   if (process.argv.includes('--check')) {
      const committed = parseGenerated(readFileSync(OUTPUT, 'utf8'));
      if (JSON.stringify(committed) !== JSON.stringify(pairs)) {
         console.error('masked-fields: the generated file differs from public.field_class');
         process.exit(1);
      }
      return;
   }
   writeFileSync(OUTPUT, render(pairs));
   // In the app's own style, so the committed file stays as written.
   spawnSync('npx', ['prettier', '--write', OUTPUT], {
      cwd: path.join(ROOT, 'app'),
      shell: process.platform === 'win32'
   });
   console.log(`masked-fields: ${pairs.length} fields`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
   try {
      main();
   } catch (error) {
      console.error(`masked-fields: ${error.message}`);
      process.exit(1);
   }
}
